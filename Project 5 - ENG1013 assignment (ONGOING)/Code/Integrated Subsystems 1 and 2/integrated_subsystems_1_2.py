"""
ENG1013 Traffic System Project
Integrated implementation for Subsystem 1 and Subsystem 2.

Subsystem 1 chosen features:
    1.R1 - Print US1 over-height alert with detected height and date/time.
    1.R2 - US1 makes TL1 yellow for 1s, then red for 30s, then green.
    1.R3 - US2 controls TL1/TL2 depending on whether US1 saw the same vehicle.
    1.R4 - Ask the user for the over-height limit, defaulting to 4.0 m.
    1.G1 - WL1 yellow LEDs alternate while TL1 or TL2 is not green.
    1.G4 - US1 and US2 are filtered using moving averages.

Subsystem 2 chosen features:
    2.R1 - Pedestrian button sequence for TL4/TL5 and PL1/PL2.
    2.R2 - Print each pedestrian request once.
    2.R3 - TL4/TL5 normal 20s/10s cycle.
    2.G1 - 30s lockout after a successful pedestrian request.
    2.G2 - PL red flashing is generated by a hardware 555 timer.
    2.G3 - DS2 changes TL4/TL5 timing at night.
    2.I1 - US5 from subsystem 3 forces TL4/TL5 red and PL1/PL2 green.

Important:
    This file includes the US5 input required for 2.I1, but it does not
    implement the rest of subsystem 3, such as TL6, DS1, FL1 or FL2.
"""

