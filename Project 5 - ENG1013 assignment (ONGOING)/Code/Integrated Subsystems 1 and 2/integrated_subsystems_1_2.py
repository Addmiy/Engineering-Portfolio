def set_pedestrian_solid_red():
    """
    Set PL1/PL2 to solid red. The 555 flash path is disabled.
    """
    set_outputs([
        (plRedSolidOutput, 1),
        (plGreenOutput, 0),
        (plRedFlashEnableOutput, 0),
    ])


def set_pedestrian_green():
    """
    Set PL1/PL2 to green. Both red paths are off.
    """
    set_outputs([
        (plRedSolidOutput, 0),
        (plGreenOutput, 1),
        (plRedFlashEnableOutput, 0),
    ])


def set_pedestrian_flashing_red():
    """
    Enable the external 555 timer so it flashes PL1/PL2 red.
    """
    set_outputs([
        (plRedSolidOutput, 0),
        (plGreenOutput, 0),
        (plRedFlashEnableOutput, 1),
    ])


def initialise_default_lights():
    """
    Put both subsystems into their normal starting states.
    """
    global s2CycleState
    global s2CycleEndTime

    set_tl1_colour("green")
    set_tl2_colour("green")
    set_outputs([(wl1LeftOutput, 0), (wl1RightOutput, 0)])

    set_pedestrian_solid_red()
    isNight, ldrValue = read_ds2_night_state()
    start_s2_cycle_state("tl4Green", time.time(), isNight)
    s2CycleState = "tl4Green"

    print("Integrated subsystem 1 + 2 started.")
    print("Over-height limit:", overheightLimitM, "m")
    print("DS2 initial A0:", ldrValue)
    print("Press Ctrl+C to stop cleanly.")


def read_filtered_distance(triggerPin, sampleList):
    """
    Read one ultrasonic sensor and return a moving average distance in cm.
    """
    reading = board.sonar_read(triggerPin)

    if reading is None or reading[0] is None:
        return None

    distanceCm = reading[0]

    if distanceCm <= 0 or distanceCm > usMaxValidDistanceCm:
        return None

    sampleList.append(distanceCm)

    if len(sampleList) > usMovingAverageWindow:
        sampleList.pop(0)

    total = 0.0
    count = 0

    for sample in sampleList:
        total = total + sample
        count = count + 1

    if count == 0:
        return None

    return total / count


def distance_to_vehicle_height(distanceCm):
    """
    Convert a model distance reading into a real-world vehicle height estimate.

    Example: if the sensor is 50 cm above the model road and represents 5 m in
    the real system, a 10 cm reading means roughly a 4 m tall vehicle.
    """
    if distanceCm is None:
        return None

    heightM = heightSensorMountHeightM * (heightSensorRoadDistanceCm - distanceCm)
    heightM = heightM / heightSensorRoadDistanceCm

    if heightM < 0:
        heightM = 0.0

    return heightM


def update_overheight_state(wasOverheight, heightM):
    """
    Apply hysteresis to avoid rapid on/off detection near the height limit.
    """
    if heightM is None:
        return 0

    if wasOverheight == 1:
        if heightM >= overheightLimitM - overheightClearMarginM:
            return 1
        return 0

    if heightM >= overheightLimitM:
        return 1

    return 0


def update_us5_presence_state(wasPresent, distanceCm):
    """
    Detect whether US5 sees a vehicle in the exit lane for 2.I1.
    """
    if distanceCm is None:
        return 0

    if wasPresent == 1:
        if distanceCm <= us5ClearDistanceCm:
            return 1
        return 0

    if distanceCm <= us5TriggerDistanceCm:
        return 1

    return 0


def read_ds2_night_state():
    """
    Return whether DS2 currently indicates night.
    """
    reading = board.analog_read(ds2AnalogPin)

    if reading is None or reading[0] is None:
        return 0, 0

    ldrValue = reading[0]

    if ldrValue <= ds2NightThreshold:
        return 1, ldrValue

    return 0, ldrValue


def print_us1_alert(heightM):
    """
    Print the 1.R1 alert once when US1 detects a new over-height vehicle.
    """
    timestamp = time.strftime("%Y-%m-%d %H:%M:%S")
    print("1.R1 ALERT:", timestamp, "- US1 detected over-height vehicle.")
    print("Detected height:", round(heightM, 2), "m")


def start_tl1_sequence(now):
    """
    Start the 1.R2 TL1 yellow -> red -> green sequence.
    """
    global tl1SequenceState
    global tl1SequenceEndTime

    if tl1SequenceState != "idle":
        return

    set_tl1_colour("yellow")
    tl1SequenceState = "yellow"
    tl1SequenceEndTime = now + tl1Tl2YellowSeconds
    print("TL1 -> YELLOW for 1 second")


def start_tl2_sequence(now):
    """
    Start the TL2 yellow -> red -> green sequence used by 1.R3.
    """
    global tl2SequenceState
    global tl2SequenceEndTime

    if tl2SequenceState != "idle":
        return

    set_tl2_colour("yellow")
    tl2SequenceState = "yellow"
    tl2SequenceEndTime = now + tl1Tl2YellowSeconds
    print("TL2 -> YELLOW for 1 second")


def update_tl1_tl2_sequences(now):
    """
    Continue any active TL1/TL2 timing sequences without blocking subsystem 2.
    """
    global tl1SequenceState
    global tl2SequenceState
    global tl1SequenceEndTime
    global tl2SequenceEndTime

    if tl1SequenceState == "yellow" and now >= tl1SequenceEndTime:
        set_tl1_colour("red")
        tl1SequenceState = "red"
        tl1SequenceEndTime = now + tl1Tl2RedSeconds
        print("TL1 -> RED for 30 seconds")
    elif tl1SequenceState == "red" and now >= tl1SequenceEndTime:
        set_tl1_colour("green")
        tl1SequenceState = "idle"
        print("TL1 -> GREEN")

    if tl2SequenceState == "yellow" and now >= tl2SequenceEndTime:
        set_tl2_colour("red")
        tl2SequenceState = "red"
        tl2SequenceEndTime = now + tl1Tl2RedSeconds
        print("TL2 -> RED for 30 seconds")
    elif tl2SequenceState == "red" and now >= tl2SequenceEndTime:
        set_tl2_colour("green")
        tl2SequenceState = "idle"
        print("TL2 -> GREEN")


def update_wl1(now):
    """
    Flash WL1 while either TL1 or TL2 is not green.
    """
    global wl1FlashState
    global wl1NextToggleTime

    if tl1Colour == "green" and tl2Colour == "green":
        set_outputs([(wl1LeftOutput, 0), (wl1RightOutput, 0)])
        return

    if now >= wl1NextToggleTime:
        wl1FlashState = 1 - wl1FlashState
        wl1NextToggleTime = now + wl1FlashHalfPeriodSeconds

        set_outputs([
            (wl1LeftOutput, wl1FlashState == 1),
            (wl1RightOutput, wl1FlashState == 0),
        ])


def update_subsystem1(now):
    """
    Read US1/US2 and trigger subsystem 1 behaviour when new detections occur.
    """
    global us1WasOverheight
    global us2WasOverheight
    global lastUs1DetectionTime

    us1DistanceCm = read_filtered_distance(us1TriggerPin, us1Samples)
    us2DistanceCm = read_filtered_distance(us2TriggerPin, us2Samples)

    us1HeightM = distance_to_vehicle_height(us1DistanceCm)
    us2HeightM = distance_to_vehicle_height(us2DistanceCm)

    us1IsOverheight = update_overheight_state(us1WasOverheight, us1HeightM)
    us2IsOverheight = update_overheight_state(us2WasOverheight, us2HeightM)

    if us1IsOverheight == 1 and us1WasOverheight == 0:
        lastUs1DetectionTime = now
        print_us1_alert(us1HeightM)
        start_tl1_sequence(now)

    if us2IsOverheight == 1 and us2WasOverheight == 0:
        sameVehicle = 0

        if lastUs1DetectionTime is not None:
            if now - lastUs1DetectionTime <= sameVehicleWindowSeconds:
                sameVehicle = 1

        if sameVehicle == 1:
            print("1.R3: US2 detected the same over-height vehicle as US1.")
            start_tl2_sequence(now)
        else:
            print("1.R3: US2 detected an over-height vehicle without recent US1 detection.")
            start_tl1_sequence(now)
            start_tl2_sequence(now)

    us1WasOverheight = us1IsOverheight
    us2WasOverheight = us2IsOverheight

    update_tl1_tl2_sequences(now)
    update_wl1(now)


def get_tl4_green_seconds(isNight):
    """
    Return the current TL4 green duration based on DS2.
    """
    if isNight == 1:
        return tl4GreenNightSeconds

    return tl4GreenDaySeconds


def get_tl5_green_seconds(isNight):
    """
    Return the current TL5 green duration based on DS2.
    """
    if isNight == 1:
        return tl5GreenNightSeconds

    return tl5GreenDaySeconds


def start_s2_cycle_state(newState, now, isNight):
    """
    Start one state in the normal TL4/TL5 2.R3 cycle.
    """
    global s2CycleState
    global s2CycleEndTime

    s2CycleState = newState

    if newState == "tl4Green":
        set_tl4_colour("green")
        set_tl5_colour("red")
        s2CycleEndTime = now + get_tl4_green_seconds(isNight)
    elif newState == "tl4Yellow":
        set_tl4_colour("yellow")
        set_tl5_colour("red")
        s2CycleEndTime = now + tl4Tl5YellowSeconds
    elif newState == "tl5Green":
        set_tl4_colour("red")
        set_tl5_colour("green")
        s2CycleEndTime = now + get_tl5_green_seconds(isNight)
    elif newState == "tl5Yellow":
        set_tl4_colour("red")
        set_tl5_colour("yellow")
        s2CycleEndTime = now + tl4Tl5YellowSeconds


def update_s2_normal_cycle(now, isNight):
    """
    Continue the normal 2.R3 TL4/TL5 cycle.
    """
    if now < s2CycleEndTime:
        return

    if s2CycleState == "tl4Green":
        start_s2_cycle_state("tl4Yellow", now, isNight)
    elif s2CycleState == "tl4Yellow":
        start_s2_cycle_state("tl5Green", now, isNight)
    elif s2CycleState == "tl5Green":
        start_s2_cycle_state("tl5Yellow", now, isNight)
    elif s2CycleState == "tl5Yellow":
        start_s2_cycle_state("tl4Green", now, isNight)


def log_ds2_change(isNight, ldrValue):
    """
    Print DS2 day/night changes only once per change.
    """
    global lastDs2NightState

    if isNight != lastDs2NightState:
        if isNight == 1:
            print("2.G3: DS2 NIGHT mode. A0 =", ldrValue)
        else:
            print("2.G3: DS2 DAY mode. A0 =", ldrValue)

        lastDs2NightState = isNight


def read_button_pressed():
    """
    Read PB1/PB2. Buttons are active-low because inputs use pull-ups.
    """
    pb1Reading = board.digital_read(pb1Pin)
    pb2Reading = board.digital_read(pb2Pin)

    pb1Value = 1
    pb2Value = 1

    if pb1Reading is not None and pb1Reading[0] is not None:
        pb1Value = pb1Reading[0]

    if pb2Reading is not None and pb2Reading[0] is not None:
        pb2Value = pb2Reading[0]

    if pb1Value == 0 or pb2Value == 0:
        return 1

    return 0


def start_pedestrian_sequence(now):
    """
    Start the 2.R1 pedestrian sequence after a valid button request.
    """
    global pedestrianState
    global pedestrianEndTime

    pedestrianState = "waitBeforeRoadStop"
    pedestrianEndTime = now + pedestrianStartDelaySeconds
    print("2.R2: pedestrian request accepted. Sequence will start after 2 seconds.")


def update_pedestrian_button(now):
    """
    Queue one pedestrian sequence when PB1/PB2 is pressed and lockout has passed.
    """
    global lastButtonPressed

    buttonPressed = read_button_pressed()

    if buttonPressed == 1 and lastButtonPressed == 0:
        if pedestrianState == "idle" and now >= pedestrianLockoutUntil:
            start_pedestrian_sequence(now)
        elif now < pedestrianLockoutUntil:
            remaining = int(pedestrianLockoutUntil - now)
            print("2.G1: pedestrian request ignored during lockout. Remaining:", remaining, "s")

    lastButtonPressed = buttonPressed


def update_pedestrian_sequence(now, isNight):
    """
    Continue the 2.R1 pedestrian sequence.
    """
    global pedestrianState
    global pedestrianEndTime
    global pedestrianRoadToStop
    global pedestrianLockoutUntil

    if pedestrianState == "idle" or now < pedestrianEndTime:
        return

    if pedestrianState == "waitBeforeRoadStop":
        if tl5Colour != "red":
            pedestrianRoadToStop = "tl5"
            set_tl5_colour("yellow")
            print("2.R1: TL5 -> YELLOW for 3 seconds")
        else:
            pedestrianRoadToStop = "tl4"
            set_tl4_colour("yellow")
            print("2.R1: TL4 -> YELLOW for 3 seconds")

        pedestrianState = "roadYellow"
        pedestrianEndTime = now + tl4Tl5YellowSeconds

    elif pedestrianState == "roadYellow":
        if pedestrianRoadToStop == "tl5":
            set_tl5_colour("red")
        else:
            set_tl4_colour("red")

        set_tl4_colour("red")
        set_tl5_colour("red")
        set_pedestrian_green()
        pedestrianState = "pedestrianGreen"
        pedestrianEndTime = now + pedestrianGreenSeconds
        print("2.R1: PL1/PL2 -> GREEN for 3 seconds")

    elif pedestrianState == "pedestrianGreen":
        set_pedestrian_flashing_red()
        pedestrianState = "pedestrianFlashRed"
        pedestrianEndTime = now + pedestrianFlashRedSeconds
        print("2.G2: PL1/PL2 -> FLASHING RED from 555 timer for 2 seconds")

    elif pedestrianState == "pedestrianFlashRed":
        set_pedestrian_solid_red()
        start_s2_cycle_state("tl4Green", now, isNight)
        pedestrianLockoutUntil = now + pedestrianLockoutSeconds
        pedestrianState = "idle"
        print("2.R1: PL1/PL2 -> SOLID RED. TL4 -> GREEN.")
        print("2.G1: 30 second pedestrian lockout started.")


def start_us5_integration(now):
    """
    Start 2.I1 when US5 detects an over-height vehicle exiting.
    """
    global pedestrianState
    global us5IntegrationState
    global us5IntegrationEndTime

    pedestrianState = "idle"
    set_pedestrian_solid_red()

    if tl4Colour != "red":
        set_tl4_colour("yellow")
        us5IntegrationState = "stoppingTl4"
        us5IntegrationEndTime = now + tl4Tl5YellowSeconds
        print("2.I1: US5 detected vehicle. TL4 -> YELLOW for 3 seconds.")
    elif tl5Colour != "red":
        set_tl5_colour("yellow")
        us5IntegrationState = "stoppingTl5"
        us5IntegrationEndTime = now + tl4Tl5YellowSeconds
        print("2.I1: US5 detected vehicle. TL5 -> YELLOW for 3 seconds.")
    else:
        set_pedestrian_green()
        us5IntegrationState = "pedestrianGreen"
        print("2.I1: TL4/TL5 already red. PL1/PL2 -> GREEN.")


def update_us5_integration(now, us5Present, isNight):
    """
    Continue the 2.I1 override sequence.
    """
    global us5IntegrationState
    global us5IntegrationEndTime

    if us5IntegrationState == "idle":
        return

    if us5IntegrationState == "stoppingTl4":
        if now < us5IntegrationEndTime:
            return

        set_tl4_colour("red")

        if tl5Colour != "red":
            set_tl5_colour("yellow")
            us5IntegrationState = "stoppingTl5"
            us5IntegrationEndTime = now + tl4Tl5YellowSeconds
            print("2.I1: TL5 -> YELLOW for 3 seconds.")
        else:
            set_pedestrian_green()
            us5IntegrationState = "pedestrianGreen"
            print("2.I1: PL1/PL2 -> GREEN while US5 detects vehicle.")

    elif us5IntegrationState == "stoppingTl5":
        if now < us5IntegrationEndTime:
            return

        set_tl5_colour("red")
        set_pedestrian_green()
        us5IntegrationState = "pedestrianGreen"
        print("2.I1: PL1/PL2 -> GREEN while US5 detects vehicle.")

    elif us5IntegrationState == "pedestrianGreen":
        set_tl4_colour("red")
        set_tl5_colour("red")
        set_pedestrian_green()

        if us5Present == 0:
            set_pedestrian_flashing_red()
            us5IntegrationState = "pedestrianFlashRed"
            us5IntegrationEndTime = now + pedestrianFlashRedSeconds
            print("2.I1: US5 clear. PL1/PL2 -> FLASHING RED for 2 seconds.")

    elif us5IntegrationState == "pedestrianFlashRed":
        if now < us5IntegrationEndTime:
            return

        set_pedestrian_solid_red()
        start_s2_cycle_state("tl4Green", now, isNight)
        us5IntegrationState = "idle"
        print("2.I1: PL1/PL2 -> SOLID RED. Normal 2.R3 cycle resumed at TL4 green.")


def update_subsystem2(now):
    """
    Read DS2, PB1/PB2 and US5, then run subsystem 2 behaviour.
    """
    global us5WasPresent

    isNight, ldrValue = read_ds2_night_state()
    log_ds2_change(isNight, ldrValue)

    us5DistanceCm = read_filtered_distance(us5TriggerPin, us5Samples)
    us5Present = update_us5_presence_state(us5WasPresent, us5DistanceCm)

    if us5Present == 1 and us5WasPresent == 0 and us5IntegrationState == "idle":
        start_us5_integration(now)

    us5WasPresent = us5Present

    if us5IntegrationState != "idle":
        update_us5_integration(now, us5Present, isNight)
        return

    update_pedestrian_button(now)

    if pedestrianState != "idle":
        update_pedestrian_sequence(now, isNight)
        return

    update_s2_normal_cycle(now, isNight)


def shutdown_system():
    """
    Turn off outputs and close the Arduino connection cleanly.
    """
    global board

    if board is None:
        return

    all_shift_outputs_off()
    time.sleep(0.2)
    board.shutdown()
    board = None


def main():
    """
    Run subsystem 1 and subsystem 2 together on one Arduino.
    """
    global overheightLimitM

    overheightLimitM = prompt_overheight_limit()
    setup_board()

    try:
        while True:
            now = time.time()
            update_subsystem1(now)
            update_subsystem2(now)
            time.sleep(loopDelaySeconds)

    except KeyboardInterrupt:
        print("\nKeyboardInterrupt received. Shutting down integrated system.")
    finally:
        shutdown_system()


if __name__ == "__main__":
    main()
