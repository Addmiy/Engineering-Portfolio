pedestrianRoadToStop = ""
pedestrianLockoutUntil = 0.0

us5IntegrationState = "idle"
us5IntegrationEndTime = 0.0


def prompt_overheight_limit():
    """
    Ask for the 1.R4 height limit. Empty input uses the 4.0 m default.
    """
    userInput = input("Enter over-height limit in metres [default 4.0]: ").strip()

    if userInput == "":
        return 4.0

    try:
        enteredLimit = float(userInput)
    except ValueError:
        print("Invalid input. Using default over-height limit of 4.0 m.")
        return 4.0

    if enteredLimit <= 0:
        print("Limit must be positive. Using default over-height limit of 4.0 m.")
        return 4.0

    return enteredLimit


def setup_board():
    """
    Connect to the Arduino and configure all direct pins.
    """
    global board

    board = pymata4.Pymata4()

    board.set_pin_mode_digital_output(shiftDataPin)
    board.set_pin_mode_digital_output(shiftLatchPin)
    board.set_pin_mode_digital_output(shiftClockPin)

    board.set_pin_mode_sonar(us1TriggerPin, us1EchoPin)
    board.set_pin_mode_sonar(us2TriggerPin, us2EchoPin)
    board.set_pin_mode_sonar(us5TriggerPin, us5EchoPin)

    board.set_pin_mode_digital_input_pullup(pb1Pin)
    board.set_pin_mode_digital_input_pullup(pb2Pin)
    board.set_pin_mode_analog_input(ds2AnalogPin)

    time.sleep(1.0)
    all_shift_outputs_off()
    initialise_default_lights()


def write_shift_registers():
    """
    Send the 24 output states to the three daisy-chained 74HC595 registers.

    Register A is nearest to the Arduino and uses output numbers 0-7.
    Register B uses 8-15. Register C uses 16-23.
    """
    board.digital_write(shiftLatchPin, 0)

    for byteNumber in [2, 1, 0]:
        byteValue = 0

        for bitNumber in range(8):
            outputIndex = byteNumber * 8 + bitNumber
            if shiftRegisterState[outputIndex] == 1:
                byteValue = byteValue | (1 << bitNumber)

        for bitNumber in range(7, -1, -1):
            board.digital_write(shiftClockPin, 0)
            board.digital_write(shiftDataPin, 1 if (byteValue & (1 << bitNumber)) else 0)
            board.digital_write(shiftClockPin, 1)

    board.digital_write(shiftLatchPin, 1)


def set_outputs(outputPairs):
    """
    Change multiple shift-register outputs at once.
    """
    changed = 0

    for outputIndex, value in outputPairs:
        newValue = 1 if value else 0

        if shiftRegisterState[outputIndex] != newValue:
            shiftRegisterState[outputIndex] = newValue
            changed = 1

    if changed == 1:
        write_shift_registers()


def all_shift_outputs_off():
    """
    Turn off every shift-register output.
    """
    for outputIndex in range(len(shiftRegisterState)):
        shiftRegisterState[outputIndex] = 0

    write_shift_registers()


