def shift_out_bits():
    """Send the current Subsystem 2 LED bits to the shift register."""
    if state["shiftRegBits"] == state["lastShiftRegBits"]:
        return

    board.digital_write(SRCLK_PIN, 0)
    board.digital_write(SER_PIN, 0)
    board.digital_write(RCLK_PIN, 0)

    for i in range(SR_LENGTH):
        board.digital_write(SER_PIN, state["shiftRegBits"][i])
        board.digital_write(SRCLK_PIN, 1)
        board.digital_write(SRCLK_PIN, 0)

    board.digital_write(RCLK_PIN, 1)
    board.digital_write(RCLK_PIN, 0)

    state["lastShiftRegBits"] = state["shiftRegBits"][:]


def TL4_red():
    state["shiftRegBits"][SR_TL4_RED] = 1
    state["shiftRegBits"][SR_TL4_YLW] = 0
    state["shiftRegBits"][SR_TL4_GRN] = 0


def TL4_yellow():
    state["shiftRegBits"][SR_TL4_RED] = 0
    state["shiftRegBits"][SR_TL4_YLW] = 1
    state["shiftRegBits"][SR_TL4_GRN] = 0


def TL4_green():
    state["shiftRegBits"][SR_TL4_RED] = 0
    state["shiftRegBits"][SR_TL4_YLW] = 0
    state["shiftRegBits"][SR_TL4_GRN] = 1


def TL5_red():
    state["shiftRegBits"][SR_TL5_RED] = 1
    state["shiftRegBits"][SR_TL5_YLW] = 0
    state["shiftRegBits"][SR_TL5_GRN] = 0


def TL5_yellow():
    state["shiftRegBits"][SR_TL5_RED] = 0
    state["shiftRegBits"][SR_TL5_YLW] = 1
    state["shiftRegBits"][SR_TL5_GRN] = 0


def TL5_green():
    state["shiftRegBits"][SR_TL5_RED] = 0
    state["shiftRegBits"][SR_TL5_YLW] = 0
    state["shiftRegBits"][SR_TL5_GRN] = 1


def PL12_green_on():
    PL12RedState["flashing"] = False
    PL12RedState["redOutput"] = 0
    board.digital_write(PL12_RED_PIN, 0)
    state["shiftRegBits"][SR_PL12_GRN] = 1


def PL12_green_off():
    state["shiftRegBits"][SR_PL12_GRN] = 0


def PL12_solid_red_on():
    """Set PL1/PL2 to solid red for normal stopped pedestrians."""
    PL12RedState["flashing"] = False
    PL12RedState["redOutput"] = 1
    board.digital_write(PL12_RED_PIN, 1)
    state["shiftRegBits"][SR_PL12_GRN] = 0


def PL12_start_flash_red():
    """Start software flashing for PL1/PL2 red."""
    PL12RedState["flashing"] = True
    PL12RedState["lastToggleTime"] = time.time()
    PL12RedState["redOutput"] = 1
    board.digital_write(PL12_RED_PIN, 1)
    state["shiftRegBits"][SR_PL12_GRN] = 0


def PL12_stop_flash_red():
    """Stop flashing and return PL1/PL2 to solid red."""
    PL12_solid_red_on()


def PL12_red_update():
    """Toggle PL1/PL2 red while software flashing is active."""
    if not PL12RedState["flashing"]:
        return

    if time.time() - PL12RedState["lastToggleTime"] >= PL12_FLASH_HALF_PERIOD:
        if PL12RedState["redOutput"] == 1:
            PL12RedState["redOutput"] = 0
        else:
            PL12RedState["redOutput"] = 1

        board.digital_write(PL12_RED_PIN, PL12RedState["redOutput"])
        state["shiftRegBits"][SR_PL12_GRN] = 0
        PL12RedState["lastToggleTime"] = time.time()


