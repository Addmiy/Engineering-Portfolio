# Shared sensor helpers
# ============================================================

def update_filtered_ldr(filter_key, raw_value):
    """Low-pass filter the LDR reading to reduce brief LED glare spikes."""
    old_value = ldr_state[filter_key]

    if old_value is None:
        ldr_state[filter_key] = float(raw_value)
    else:
        ldr_state[filter_key] = (
            old_value * (1.0 - LDR_FILTER_ALPHA)
            + float(raw_value) * LDR_FILTER_ALPHA
        )

    return ldr_state[filter_key]


def ldr_value_is_night(
    value,
    was_night,
    night_threshold,
    day_threshold,
    bright_reading_is_low,
):
    """Convert a filtered LDR value into night/day using hysteresis."""
    if bright_reading_is_low:
        if was_night:
            return value > day_threshold
        return value >= night_threshold

    if was_night:
        return value < night_threshold
    return value <= day_threshold


def read_daylight():
    """Read DS2 and update Subsystem 2 day/night timing mode."""
    reading = board.analog_read(DS2_PIN)

    if reading is None or reading[0] is None:
        return

    value = reading[0]
    was_night = state["DS2nightTime"]
    filtered_value = update_filtered_ldr("DS2Filtered", value)
    state["DS2nightTime"] = ldr_value_is_night(
        filtered_value,
        was_night,
        DS_NIGHT_BOUNDARY,
        DS_DAY_BOUNDARY,
        DS2_BRIGHT_READING_IS_LOW,
    )

    if state["DS2nightTime"] != was_night:
        if state["DS2nightTime"]:
            print("[SUB2] DS2 NIGHT detected. DS2 =", value)
        else:
            print("[SUB2] DS2 DAY detected. DS2 =", value)


def read_ds1_state(us5_present):
    """Read DS1. Return 1 for night and 0 for day."""
    reading = board.analog_read(DS1_ANALOG_PIN)

    if reading is None or reading[0] is None:
        if ldr_state["DS1nightTime"]:
            return 1, 0
        return 0, 0

    value = reading[0]
    filtered_value = update_filtered_ldr("DS1Filtered", value)
    was_night = ldr_state["DS1nightTime"]

    # If the event started at night, keep treating it as night until TL6 has
    # finished. This stops FL1/FL2 or nearby LEDs from fooling DS1 mid-event.
    if was_night and (us5_present == 1 or sub3_mode != "RED_IDLE"):
        return 1, value

    ldr_state["DS1nightTime"] = ldr_value_is_night(
        filtered_value,
        was_night,
        NIGHT_LDR_THRESHOLD,
        DS1_DAY_THRESHOLD,
        DS1_BRIGHT_READING_IS_LOW,
    )

    if ldr_state["DS1nightTime"]:
        return 1, value

    return 0, value


def log_ds1_change(is_night, ldr_value):
    """Print DS1 day/night changes without spamming the console."""
    global last_ds1_state

    if is_night != last_ds1_state:
        if is_night == 1:
            print("[SUB3] DS1 NIGHT detected. DS1 =", ldr_value)
        else:
            print("[SUB3] DS1 DAY detected. DS1 =", ldr_value)
        last_ds1_state = is_night


def read_us5_filtered_distance():
    """Read US5 and return a moving-average distance in centimetres."""
    reading = board.sonar_read(US5_TRIGGER_PIN)

    if reading is None or reading[0] is None:
        return None

    distance_cm = reading[0]

    if distance_cm <= 0:
        return None

    if distance_cm > US5_MAX_VALID_DISTANCE_CM:
        return None

    us5_samples.append(distance_cm)

    if len(us5_samples) > US5_MOVING_AVERAGE_WINDOW:
        us5_samples.pop(0)

    total = 0.0
    sample_count = 0

    for sample in us5_samples:
        total = total + sample
        sample_count = sample_count + 1

    if sample_count == 0:
        return None

    return total / sample_count


def calculate_us5_presence(currently_active, filtered_distance):
    """Apply trigger/clear thresholds to the filtered US5 distance."""
    if filtered_distance is None:
        return 0

    if currently_active == 1:
        if filtered_distance <= EXIT_LANE_CLEAR_DISTANCE_CM:
            return 1
        return 0

    if filtered_distance <= EXIT_LANE_TRIGGER_DISTANCE_CM:
        return 1

    return 0


