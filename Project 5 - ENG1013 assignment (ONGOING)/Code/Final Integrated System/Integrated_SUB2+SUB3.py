def enter_mode(new_mode):
    """Switch Subsystem 2 to a new mode and remember when it started."""
    state["sub2Mode"] = new_mode
    state["sub2ModeStartTime"] = time.time()

    # Lock the green duration when a phase starts. DS2 changes then apply to
    # the next phase, instead of shortening or lengthening the current one.
    if new_mode == MODE_TL4_GREEN:
        if state["DS2nightTime"]:
            state["sub2GreenDuration"] = TL4_GREEN_NIGHT
        else:
            state["sub2GreenDuration"] = TL4_GREEN_DAY
    elif new_mode == MODE_TL5_GREEN:
        if state["DS2nightTime"]:
            state["sub2GreenDuration"] = TL5_GREEN_NIGHT
        else:
            state["sub2GreenDuration"] = TL5_GREEN_DAY


def start_yellow(which_tl, after_mode):
    """Start a 3 second yellow phase on TL4 or TL5."""
    if which_tl == "TL4":
        TL4_yellow()
    else:
        TL5_yellow()

    state["sub2YellowWhich"] = which_tl
    state["sub2YellowAfter"] = after_mode
    enter_mode(MODE_YELLOW)


def start_emergency():
    """Queue the overheight response without cutting short TL4/TL5 green."""
    state["sub2PedRequestPending"] = False
    if state["sub2EmergencyStartTime"] == 0.0:
        state["sub2EmergencyStartTime"] = time.time()

    mode = state["sub2Mode"]

    if mode in (MODE_TL4_GREEN, MODE_TL5_GREEN):
        if not state["sub2EmergencyQueuedPrinted"]:
            print("[SUB2] OVERHEIGHT detected - waiting for current TL4/TL5 sequence to finish")
            state["sub2EmergencyQueuedPrinted"] = True
    elif mode == MODE_YELLOW:
        # If a yellow phase is already running, finish that one yellow phase
        # and go to the overheight hold. Do not restart or re-print each loop.
        if not state["sub2EmergencyQueuedPrinted"]:
            print("[SUB2] OVERHEIGHT detected - waiting for current yellow to finish")
            state["sub2EmergencyQueuedPrinted"] = True
        state["sub2YellowAfter"] = MODE_EMERG_HOLD
    else:
        TL4_red()
        TL5_red()
        PL12_stop_flash_red()
        PL12_green_on()
        enter_mode(MODE_EMERG_HOLD)


def do_TL4_green():
    """Normal TL4 green phase with day/night timing from DS2."""
    green_time = state["sub2GreenDuration"]
    elapsed = time.time() - state["sub2ModeStartTime"]

    if state["sub2OverheightDetected"]:
        state["sub2PedRequestPending"] = False
        if elapsed >= green_time:
            start_yellow("TL4", MODE_EMERG_HOLD)
        return

    if state["sub2PedRequestPending"]:
        if time.time() - state["sub2PedRequestTime"] >= PED_WAIT:
            start_yellow("TL4", MODE_PED_WALK)
        return

    if elapsed >= green_time:
        start_yellow("TL4", MODE_TL5_GREEN)


def do_TL5_green():
    """Normal TL5 green phase with day/night timing from DS2."""
    green_time = state["sub2GreenDuration"]
    elapsed = time.time() - state["sub2ModeStartTime"]

    if state["sub2OverheightDetected"]:
        state["sub2PedRequestPending"] = False
        if elapsed >= green_time:
            start_yellow("TL5", MODE_EMERG_HOLD)
        return

    if state["sub2PedRequestPending"]:
        if time.time() - state["sub2PedRequestTime"] >= PED_WAIT:
            start_yellow("TL5", MODE_PED_WALK)
        return

    if elapsed >= green_time:
        start_yellow("TL5", MODE_TL4_GREEN)


def do_yellow():
    """Finish the active yellow phase after 3 seconds."""
    elapsed = time.time() - state["sub2ModeStartTime"]

    if elapsed < YELLOW_TIME:
        return

    which = state["sub2YellowWhich"]

    if which == "TL4":
        TL4_red()
    else:
        TL5_red()

    next_mode = state["sub2YellowAfter"]

    if next_mode == MODE_TL4_GREEN:
        TL4_green()
        TL5_red()
    elif next_mode == MODE_TL5_GREEN:
        TL4_red()
        TL5_green()
    elif next_mode == MODE_PED_WALK:
        state["sub2PedRequestPending"] = False
        PL12_green_on()
        print("[SUB2] PL1 + PL2 GREEN (walk)")
    elif next_mode == MODE_EMERG_HOLD:
        TL4_red()
        TL5_red()
        PL12_stop_flash_red()
        PL12_green_on()
        print("[SUB2] TL4/TL5 are RED - TL6 may start after the 3s minimum delay")

    enter_mode(next_mode)


def do_ped_wait():
    """Compatibility mode only; pedestrian waiting is handled before yellow."""
    PL12_green_on()
    print("[SUB2] PL1 + PL2 GREEN (walk)")
    enter_mode(MODE_PED_WALK)


def do_ped_walk():
    """Keep PL1/PL2 green for 3 seconds."""
    elapsed = time.time() - state["sub2ModeStartTime"]

    if elapsed >= PED_GREEN_TIME:
        PL12_green_off()
        PL12_start_flash_red()
        print("[SUB2] PL1 + PL2 flashing RED (2s)")
        enter_mode(MODE_PED_FLASH)


def do_ped_flash():
    """Flash PL1/PL2 red for 2 seconds, then start the 30 second lockout."""
    elapsed = time.time() - state["sub2ModeStartTime"]

    if elapsed >= PED_FLASH_TIME:
        PL12_stop_flash_red()
        TL4_green()
        TL5_red()
        state["sub2Lockout"] = True
        state["sub2LockoutStartTime"] = time.time()
        state["sub2PedRequestPending"] = False
        print("[SUB2] Crossing complete - 30s lockout started")
        enter_mode(MODE_TL4_GREEN)


def do_emerg_hold():
    """Hold TL4/TL5 red and PL1/PL2 green while US5 detects the vehicle."""
    TL4_red()
    TL5_red()
    PL12_green_on()

    if not state["sub2OverheightDetected"]:
        PL12_green_off()
        PL12_start_flash_red()
        state["sub2WaitingForTL6RedPrinted"] = False
        print("[SUB2] Overheight cleared - PL1/PL2 flashing RED (2s)")
        enter_mode(MODE_EMERG_FLASH)


def do_emerg_flash():
    """After US5 clears, wait for TL6 red before resuming TL4/TL5 traffic."""
    elapsed = time.time() - state["sub2ModeStartTime"]

    # Keep Tunnel Ave stopped until both safety conditions are true:
    # 1. PL1/PL2 has flashed red for at least 2 seconds.
    # 2. TL6 has completed its green/yellow/red sequence and is fully red.
    TL4_red()
    TL5_red()

    if elapsed < PED_FLASH_TIME:
        return

    if sub3_mode != "RED_IDLE":
        if not state["sub2WaitingForTL6RedPrinted"]:
            print("[SUB2] Waiting for TL6 to turn RED before TL4/TL5 resume")
            state["sub2WaitingForTL6RedPrinted"] = True
        return

    PL12_stop_flash_red()
    TL4_green()
    TL5_red()
    state["sub2EmergencyStartTime"] = 0.0
    state["sub2EmergencyQueuedPrinted"] = False
    print("[SUB2] TL6 is RED. Emergency response done - normal cycle resumes")
    enter_mode(MODE_TL4_GREEN)


def check_buttons():
    """Read PB1/PB2 and queue one pedestrian request per press."""
    pb1_reading = board.digital_read(PB1_PIN)
    pb2_reading = board.digital_read(PB2_PIN)

    pb1_value = 1
    pb2_value = 1

    if pb1_reading is not None and pb1_reading[0] is not None:
        pb1_value = pb1_reading[0]

    if pb2_reading is not None and pb2_reading[0] is not None:
        pb2_value = pb2_reading[0]

    # The supplied Sub2 standalone uses active-low buttons.
    pb1_pressed = pb1_value == 0
    pb2_pressed = pb2_value == 0
    pressed_now = pb1_pressed or pb2_pressed

    was_pressed = state["sub2PBwasPressed"]

    if pressed_now and not was_pressed:
        request_already_active = (
            state["sub2PedRequestPending"]
            or state["sub2Mode"] in (MODE_PED_WAIT, MODE_PED_WALK, MODE_PED_FLASH)
            or (
                state["sub2Mode"] == MODE_YELLOW
                and state["sub2YellowAfter"] == MODE_PED_WALK
            )
        )

        if not state["sub2Lockout"] and not request_already_active:
            if pb1_pressed:
                print("[SUB2] Pedestrian request received from PB1")
            else:
                print("[SUB2] Pedestrian request received from PB2")
            state["sub2PedRequestPending"] = True
            state["sub2PedRequestTime"] = time.time()

    state["sub2PBwasPressed"] = pressed_now


def update_lockout():
    """Clear the 30 second pedestrian lockout when it expires."""
    if state["sub2Lockout"]:
        if time.time() - state["sub2LockoutStartTime"] >= PED_LOCKOUT:
            state["sub2Lockout"] = False
            print("[SUB2] Pedestrian lockout finished")


def update_pending_pedestrian_yellow_request():
    """If PB1/PB2 was pressed during yellow, finish that yellow then walk."""
    if not state["sub2PedRequestPending"]:
        return

    if state["sub2Mode"] != MODE_YELLOW:
        return

    if state["sub2YellowAfter"] == MODE_EMERG_HOLD:
        return

    if time.time() - state["sub2PedRequestTime"] >= PED_WAIT:
        state["sub2YellowAfter"] = MODE_PED_WALK


def sub2_traffic_is_stopped():
    """Return True once TL4/TL5 are red and the 3.I1 minimum delay has passed."""
    if state["sub2Mode"] != MODE_EMERG_HOLD:
        return False

    if state["sub2EmergencyStartTime"] == 0.0:
        return False

    return time.time() - state["sub2EmergencyStartTime"] >= MINIMUM_TL6_RELEASE_DELAY


def sub2_update():
    """Run one update of Subsystem 2."""
    update_lockout()

    if (
        not state["sub2OverheightDetected"]
        and state["sub2Mode"] in (MODE_TL4_GREEN, MODE_TL5_GREEN)
    ):
        state["sub2EmergencyStartTime"] = 0.0
        state["sub2EmergencyQueuedPrinted"] = False

    # Pedestrian buttons are ignored while the overheight override is active.
    if not state["sub2OverheightDetected"]:
        check_buttons()
    else:
        state["sub2PedRequestPending"] = False

    update_pending_pedestrian_yellow_request()

    if state["sub2OverheightDetected"]:
        mode = state["sub2Mode"]
        if mode == MODE_EMERG_FLASH:
            PL12_stop_flash_red()
            PL12_green_on()
            enter_mode(MODE_EMERG_HOLD)
        elif mode not in (MODE_YELLOW, MODE_EMERG_HOLD, MODE_EMERG_FLASH):
            start_emergency()
        elif mode == MODE_YELLOW:
            if state["sub2EmergencyStartTime"] == 0.0:
                state["sub2EmergencyStartTime"] = time.time()
            if not state["sub2EmergencyQueuedPrinted"]:
                print("[SUB2] OVERHEIGHT detected - waiting for current yellow to finish")
                state["sub2EmergencyQueuedPrinted"] = True
            state["sub2PedRequestPending"] = False
            state["sub2YellowAfter"] = MODE_EMERG_HOLD

    mode = state["sub2Mode"]

    if mode == MODE_TL4_GREEN:
        do_TL4_green()
    elif mode == MODE_TL5_GREEN:
        do_TL5_green()
    elif mode == MODE_YELLOW:
        do_yellow()
    elif mode == MODE_PED_WAIT:
        do_ped_wait()
    elif mode == MODE_PED_WALK:
        do_ped_walk()
    elif mode == MODE_PED_FLASH:
        do_ped_flash()
    elif mode == MODE_EMERG_HOLD:
        do_emerg_hold()
    elif mode == MODE_EMERG_FLASH:
        do_emerg_flash()


