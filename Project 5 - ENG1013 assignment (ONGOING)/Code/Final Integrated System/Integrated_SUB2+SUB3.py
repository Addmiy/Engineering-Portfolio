def setup_board():
    """Connect to the Arduino and configure every Subsystem 2 and 3 pin."""
    global board

    if BOARD_COM_PORT is None:
        board = pymata4.Pymata4()
    else:
        board = pymata4.Pymata4(com_port=BOARD_COM_PORT)

    # Subsystem 2 outputs and inputs
    board.set_pin_mode_digital_output(SRCLK_PIN)
    board.set_pin_mode_digital_output(RCLK_PIN)
    board.set_pin_mode_digital_output(SER_PIN)
    board.set_pin_mode_digital_output(PL12_RED_PIN)
    board.set_pin_mode_digital_input(PB1_PIN)
    board.set_pin_mode_digital_input(PB2_PIN)
    board.set_pin_mode_analog_input(DS2_PIN)

    # Subsystem 3 outputs and inputs
    board.set_pin_mode_digital_output(TL6_RED_PIN)
    board.set_pin_mode_digital_output(TL6_YELLOW_PIN)
    board.set_pin_mode_digital_output(TL6_GREEN_PIN)
    board.set_pin_mode_digital_output(FL1_PIN)
    board.set_pin_mode_digital_output(FL2_PIN)
    board.set_pin_mode_analog_input(DS1_ANALOG_PIN)
    board.set_pin_mode_sonar(US5_TRIGGER_PIN, US5_ECHO_PIN)

    time.sleep(1.0)

    setup_initial_outputs()


def setup_initial_outputs():
    """Set the starting state: TL4 green, TL5 red, PL solid red, TL6 red."""
    state["shiftRegBits"] = [0] * SR_LENGTH
    state["lastShiftRegBits"] = [1] * SR_LENGTH

    TL4_green()
    TL5_red()
    PL12_green_off()
    PL12_solid_red_on()
    shift_out_bits()

    set_tl6_red()
    set_floodlights(0)

    state["sub2Mode"] = MODE_TL4_GREEN
    state["sub2ModeStartTime"] = time.time()
    state["sub2GreenDuration"] = TL4_GREEN_DAY

    print("Integrated Subsystem 2 + Subsystem 3 started.")
    if DS1_BRIGHT_READING_IS_LOW:
        print("DS1 mode: low analog reading = bright/day.")
    else:
        print("DS1 mode: high analog reading = bright/day.")
    if DS2_BRIGHT_READING_IS_LOW:
        print("DS2 mode: low analog reading = bright/day.")
    else:
        print("DS2 mode: high analog reading = bright/day.")
    if DS2_BRIGHT_READING_IS_LOW:
        print("DS2 Thresholds: night >=", DS_NIGHT_BOUNDARY, "day <=", DS_DAY_BOUNDARY)
    else:
        print("DS2 Thresholds: day >=", DS_NIGHT_BOUNDARY, "night <=", DS_DAY_BOUNDARY)
    if DS1_BRIGHT_READING_IS_LOW:
        print("DS1 Thresholds: night >=", NIGHT_LDR_THRESHOLD, "day <=", DS1_DAY_THRESHOLD)
    else:
        print("DS1 Thresholds: day >=", NIGHT_LDR_THRESHOLD, "night <=", DS1_DAY_THRESHOLD)
    print("Press Ctrl+C to stop.")


def shutdown_system():
    """Turn all outputs off before closing the Arduino connection."""
    global board

    if board is None:
        return

    try:
        state["shiftRegBits"] = [0] * SR_LENGTH
        state["lastShiftRegBits"] = [1] * SR_LENGTH
        shift_out_bits()
        board.digital_write(PL12_RED_PIN, 0)
        set_tl6_all_off()
        set_floodlights(0)
        time.sleep(0.2)
        board.shutdown()
    except Exception:
        pass

    board = None


