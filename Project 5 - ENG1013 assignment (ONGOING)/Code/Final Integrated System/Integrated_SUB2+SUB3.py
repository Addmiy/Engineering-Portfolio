def get_tl6_green_time(ds1_night):
    """Return TL6 green time: 5 seconds by day, 10 seconds by night."""
    if ds1_night == 1:
        return NIGHT_GREEN_SECONDS

    return DAY_GREEN_SECONDS


def start_tl6_green(ds1_night, filtered_distance):
    """Start the TL6 green stage after Subsystem 2 is safely stopped."""
    global sub3_mode
    global sub3_mode_start_time
    global sub3_green_time

    sub3_green_time = get_tl6_green_time(ds1_night)
    set_tl6_green()
    sub3_mode = "GREEN_MINIMUM"
    sub3_mode_start_time = time.time()

    if filtered_distance is not None:
        print("[SUB3] US5 detected vehicle at", round(filtered_distance, 2), "cm")

    if ds1_night == 1:
        print("[SUB3] TL6 GREEN for at least 10 seconds because DS1 is night")
    else:
        print("[SUB3] TL6 GREEN for at least 5 seconds")


def sub3_update(us5_present, filtered_distance, ds1_night):
    """Run one update of Subsystem 3 without blocking Subsystem 2."""
    global sub3_mode
    global sub3_mode_start_time

    # 3.G3: floodlights stay on only while US5 detects a vehicle at night.
    set_floodlights(us5_present == 1 and ds1_night == 1)

    if sub3_mode == "RED_IDLE":
        set_tl6_red()

        if us5_present == 1:
            sub3_mode = "WAITING_FOR_SUB2"
            sub3_mode_start_time = time.time()
            print("[SUB3] 3.I1: waiting for TL4/TL5 to turn red")

    elif sub3_mode == "WAITING_FOR_SUB2":
        set_tl6_red()

        if us5_present == 0:
            sub3_mode = "RED_IDLE"
            print("[SUB3] US5 cleared before TL6 green")
        elif sub2_traffic_is_stopped():
            start_tl6_green(ds1_night, filtered_distance)

    elif sub3_mode == "GREEN_MINIMUM":
        set_tl6_green()

        elapsed = time.time() - sub3_mode_start_time

        if elapsed >= sub3_green_time:
            if us5_present == 1:
                sub3_mode = "GREEN_HOLD"
                print("[SUB3] 3.R2: TL6 holding solid GREEN until US5 clears")
            else:
                set_tl6_yellow()
                sub3_mode = "YELLOW"
                sub3_mode_start_time = time.time()
                print("[SUB3] TL6 -> YELLOW for 3 seconds")

    elif sub3_mode == "GREEN_HOLD":
        set_tl6_green()

        if us5_present == 0:
            set_tl6_yellow()
            sub3_mode = "YELLOW"
            sub3_mode_start_time = time.time()
            print("[SUB3] US5 clear. TL6 -> YELLOW for 3 seconds")

    elif sub3_mode == "YELLOW":
        set_tl6_yellow()

        elapsed = time.time() - sub3_mode_start_time

        if elapsed >= TL6_YELLOW_SECONDS:
            set_tl6_red()
            sub3_mode = "RED_IDLE"
            print("[SUB3] TL6 -> RED")


# ============================================================
# Main loop
# ============================================================

def main():
    """Main integrated controller loop."""
    global last_us5_present

    setup_board()

    try:
        while True:
            read_daylight()

            filtered_distance = read_us5_filtered_distance()
            us5_present = calculate_us5_presence(last_us5_present, filtered_distance)

            ds1_night, ds1_value = read_ds1_state(us5_present)
            log_ds1_change(ds1_night, ds1_value)

            if us5_present != last_us5_present:
                if us5_present == 1:
                    print("[US5] Overheight vehicle detected")
                else:
                    print("[US5] Overheight vehicle cleared")
                    us5_samples.clear()

            state["sub2OverheightDetected"] = bool(us5_present)

            sub2_update()
            sub3_update(us5_present, filtered_distance, ds1_night)

            PL12_red_update()
            shift_out_bits()

            last_us5_present = us5_present
            time.sleep(POLL_DELAY_SECONDS)

    except KeyboardInterrupt:
        print("\nKeyboardInterrupt received. Shutting down integrated controller.")
    finally:
        shutdown_system()


if __name__ == "__main__":
    main()
